#!/usr/bin/env python3
"""Settings typed into postgresql.conf by hand, and what a restart does with
them.

Patroni regenerates the file from the DCS at every start, restart and reload,
so a hand edit is one restart away from vanishing. The tests pin that such
edits are found by provenance — in the file, in neither the DCS nor the
node's YAML, and not something Patroni writes itself — and are moved into the
DCS before anything regenerates the file.
"""

import pytest

from aspects import cluster_services, patroni_management as pm

from conftest import FakeExecutor, RecordingLogger

PATRONI_FILE = """# Do not edit this file manually!
# It will be overwritten by Patroni!
include 'postgresql.base.conf'

cluster_name = 'pgedge-n1'
hot_standby = 'on'
listen_addresses = '0.0.0.0'
max_connections = '100'
port = '5432'
shared_preload_libraries = 'spock'
track_commit_timestamp = 'on'
wal_level = 'logical'
log_min_messages = 'debug1'
hba_file = '/var/lib/pgedge/n1/pg_hba.conf'
"""

HAND_EDITS = """
# added by hand on Tuesday
work_mem = 64MB
shared_buffers = '2GB'   # a quarter of RAM
spock.exception_behaviour = 'transdiscard'
"""


class DcsExecutor(FakeExecutor):
    """A FakeExecutor whose show-config reflects the edit-configs it saw —
    the DCS as a thing with state, not a fixed answer."""

    def __init__(self, conf, dcs=None, **extra):
        super().__init__(replies=extra)
        self.conf = conf
        self.dcs = dict(dcs if dcs is not None else {
            "log_min_messages": "debug1", "shared_preload_libraries": "spock",
            "track_commit_timestamp": "on"})

    def _answer(self, command):
        if "postgresql.conf" in command and command.startswith("cat "):
            self.commands.append(command)
            return True, self.conf
        if "edit-config" in command and "edit-config" not in self.replies:
            self.commands.append(command)
            for part in command.split(" -s ")[1:]:
                setting = part.split(" 2>&1")[0].strip().strip("'")
                key, _, value = setting.partition("=")
                self.dcs[key.replace("postgresql.parameters.", "")] = value
            return True, ""
        if "show-config" in command:
            self.commands.append(command)
            return True, ("postgresql:\n  parameters:\n"
                          + "".join(f"    {k}: {v}\n"
                                    for k, v in self.dcs.items()))
        return super()._answer(command)


def executor_with(conf, dcs=None, **extra):
    return DcsExecutor(conf, dcs=dcs, **extra)


# ---------------------------------------------------------------------------
# reading the file
# ---------------------------------------------------------------------------


def test_the_file_is_read_the_way_the_server_reads_it():
    settings = pm.parse_conf_settings(PATRONI_FILE + HAND_EDITS)

    assert settings["work_mem"] == "64MB"
    assert settings["shared_buffers"] == "2GB", "quotes and trailing comment gone"
    assert settings["spock.exception_behaviour"] == "transdiscard"
    assert "include" not in settings


def test_a_later_line_wins_as_it_does_for_the_server():
    assert pm.parse_conf_settings("work_mem = 4MB\nwork_mem = 64MB\n") == \
        {"work_mem": "64MB"}


# ---------------------------------------------------------------------------
# what counts as a hand edit
# ---------------------------------------------------------------------------


def test_only_what_patroni_did_not_write_is_a_hand_edit(deployed_plan):
    """Everything Patroni renders — from the DCS, from the YAML, or of its
    own accord — is not an override, however it appears in the file."""
    executor = executor_with(PATRONI_FILE + HAND_EDITS)

    overrides = pm.local_overrides(executor, deployed_plan,
                                   deployed_plan.node("n1"))

    assert overrides == {"work_mem": "64MB", "shared_buffers": "2GB",
                         "spock.exception_behaviour": "transdiscard"}


def test_a_file_patroni_wrote_untouched_has_no_overrides(deployed_plan):
    executor = executor_with(PATRONI_FILE)

    assert pm.local_overrides(executor, deployed_plan,
                              deployed_plan.node("n1")) == {}


def test_a_replica_connection_is_never_treated_as_a_hand_edit(deployed_plan):
    """primary_conninfo is Patroni's, per member; copying it into the scope
    would point the leader at itself."""
    executor = executor_with(
        PATRONI_FILE + "primary_conninfo = 'host=10.0.1.11 port=5432'\n"
                       "primary_slot_name = 'n1s1'\n")

    assert pm.local_overrides(executor, deployed_plan,
                              deployed_plan.node("n1")) == {}


def test_a_setting_already_in_the_dcs_is_not_an_override(deployed_plan):
    """It will be rendered again from the DCS; nothing to lose."""
    executor = executor_with(PATRONI_FILE + "work_mem = '64MB'\n",
                             dcs={"work_mem": "64MB", "log_min_messages": "debug1"})

    assert pm.local_overrides(executor, deployed_plan,
                              deployed_plan.node("n1")) == {}


def test_a_missing_file_means_nothing_to_keep(deployed_plan):
    executor = FakeExecutor(replies={"cat ": (False, "")})

    assert pm.local_overrides(executor, deployed_plan,
                              deployed_plan.node("n1")) == {}


# ---------------------------------------------------------------------------
# keeping them
# ---------------------------------------------------------------------------


def test_hand_edits_are_moved_into_the_scope_dcs(deployed_plan):
    executor = executor_with(PATRONI_FILE + HAND_EDITS)
    log = RecordingLogger()

    ok, kept, message = pm.preserve_local_overrides(
        executor, deployed_plan, deployed_plan.node("n1"), run_logger=log)

    assert ok and set(kept) == {"work_mem", "shared_buffers",
                                "spock.exception_behaviour"}
    edit = next(c for c in executor.commands if "edit-config" in c)
    assert "pgedge-n1" in edit and "--force" in edit
    assert "postgresql.parameters.work_mem=64MB" in edit
    assert "postgresql.parameters.shared_buffers=2GB" in edit
    assert "kept 3 setting(s)" in message


def test_nothing_to_keep_writes_nothing(deployed_plan):
    executor = executor_with(PATRONI_FILE)

    ok, kept, message = pm.preserve_local_overrides(
        executor, deployed_plan, deployed_plan.node("n1"))

    assert ok and kept == {} and message == ""
    assert not executor.ran("edit-config")


def test_an_edit_config_that_did_not_take_is_reported_not_trusted(deployed_plan):
    """show-config afterwards is the proof; without it the restart would go
    ahead and the settings would be gone."""
    # An edit-config that is accepted but changes nothing in the DCS.
    executor = executor_with(PATRONI_FILE + "work_mem = 64MB\n",
                             **{"edit-config": (True, "")})

    ok, kept, message = pm.preserve_local_overrides(
        executor, deployed_plan, deployed_plan.node("n1"))

    assert not ok and kept == {}
    assert "does not show work_mem" in message


# ---------------------------------------------------------------------------
# through restart and reload
# ---------------------------------------------------------------------------


def patroni_ready(conf):
    return executor_with(conf)


@pytest.mark.parametrize("component", ["postgres", "patroni"])
def test_a_restart_keeps_hand_edits_before_patroni_regenerates(deployed_plan,
                                                              component):
    executor = patroni_ready(PATRONI_FILE + "work_mem = 64MB\n")

    ok, message = cluster_services.restart(executor, deployed_plan,
                                           deployed_plan.node("n1"),
                                           component=component)

    assert ok, message
    commands = executor.commands
    edit = next(i for i, c in enumerate(commands) if "edit-config" in c)
    restart = next(i for i, c in enumerate(commands)
                   if " restart " in c or "systemctl restart" in c)
    assert edit < restart, "kept first, then restarted"
    assert "kept 1 setting(s)" in message and "work_mem" in message


def test_a_reload_keeps_them_too(deployed_plan):
    """patronictl reload regenerates the file exactly as a restart does."""
    executor = patroni_ready(PATRONI_FILE + "work_mem = 64MB\n")

    ok, message = cluster_services.reload(executor, deployed_plan,
                                          deployed_plan.node("n1"),
                                          component="postgres")

    assert ok and "work_mem" in message
    assert executor.ran("edit-config")


def test_a_restart_that_cannot_keep_them_does_not_restart(deployed_plan):
    """Losing the settings silently is the one outcome that must not happen."""
    executor = executor_with(PATRONI_FILE + "work_mem = 64MB\n",
                             **{"edit-config": (False, "etcd unreachable")})

    ok, message = cluster_services.restart(executor, deployed_plan,
                                           deployed_plan.node("n1"),
                                           component="postgres")

    assert not ok
    assert "not restarted" in message and "would be lost" in message
    assert not any(" restart " in c for c in executor.commands)


def test_discarding_is_a_choice_not_a_default(deployed_plan):
    executor = patroni_ready(PATRONI_FILE + "work_mem = 64MB\n")

    ok, message = cluster_services.restart(executor, deployed_plan,
                                           deployed_plan.node("n1"),
                                           component="postgres", preserve=False)

    assert ok
    assert not executor.ran("edit-config")
    assert "kept" not in message


def test_the_cli_flag_passes_the_choice_through(monkeypatch, deployed_plan):
    import types
    from deployment import ops_cli

    seen = {}
    monkeypatch.setattr(ops_cli, "_load", lambda args: (deployed_plan, {}))
    monkeypatch.setattr(ops_cli, "_with_pool",
                        lambda plan, handler: handler(lambda node: FakeExecutor()))
    monkeypatch.setattr(ops_cli.cluster_services, "restart",
                        lambda e, p, n, component, preserve=True:
                        seen.update(preserve=preserve) or (True, "ok"))

    args = types.SimpleNamespace(service_action="restart", node="n1",
                                 component="postgres", json=False,
                                 discard_local_settings=True, cluster=None,
                                 db_password=None, inventory=None)
    assert ops_cli.cmd_service(args) == 0
    assert seen == {"preserve": False}


def test_the_bootstrap_parameters_count_as_managed_without_show_config(deployed_plan):
    """An older Patroni that cannot answer show-config must not make every
    setting this tool seeded look like a hand edit."""
    executor = executor_with(PATRONI_FILE + "work_mem = 64MB\n", dcs={})

    overrides = pm.local_overrides(executor, deployed_plan,
                                   deployed_plan.node("n1"))

    assert overrides == {"work_mem": "64MB"}
